create table public.payments (
  id uuid primary key default gen_random_uuid(),
  enrollment_id uuid not null references public.student_enrollments(id) on delete restrict,
  fee_tariff_id uuid not null references public.fee_tariffs(id) on delete restrict,
  cashier_id uuid not null references public.profiles(id) on delete restrict,
  amount_paid numeric(14,2) not null check(amount_paid > 0),
  currency char(3) not null check(currency in ('USD','CDF')),
  payment_reference text not null unique,
  payment_date timestamptz not null default now(),
  notes text,
  status text not null default 'VALIDE' check(status in ('VALIDE','ANNULE')),
  annulled_at timestamptz,
  annulled_by uuid references public.profiles(id) on delete restrict,
  annulment_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (status = 'VALIDE' and annulled_at is null and annulled_by is null and annulment_reason is null)
    or
    (status = 'ANNULE' and annulled_at is not null and annulled_by is not null
      and annulment_reason is not null and length(btrim(annulment_reason)) > 0)
  )
);
create index payments_enrollment_date_idx on public.payments(enrollment_id, payment_date desc);
