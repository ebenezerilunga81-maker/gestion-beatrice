create table public.fee_tariff_templates (
  id uuid primary key default gen_random_uuid(),
  fee_type_id smallint not null references public.fee_types(id) on delete restrict,
  category_id smallint not null references public.categories(id) on delete restrict,
  class_id smallint not null,
  amount numeric(14,2) not null check(amount >= 0),
  currency char(3) not null check(currency in ('USD','CDF')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  foreign key(class_id, category_id)
    references public.classes(id, category_id) on delete restrict,
  unique(fee_type_id, class_id)
);

create table public.fee_tariffs (
  id uuid primary key default gen_random_uuid(),
  school_year_id uuid not null references public.school_years(id) on delete restrict,
  fee_type_id smallint not null references public.fee_types(id) on delete restrict,
  category_id smallint not null references public.categories(id) on delete restrict,
  class_id smallint not null,
  amount numeric(14,2) not null check(amount >= 0),
  currency char(3) not null check(currency in ('USD','CDF')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  foreign key(class_id, category_id)
    references public.classes(id, category_id) on delete restrict,
  unique(school_year_id, fee_type_id, class_id)
);

create function app_private.copy_tariffs_for_year()
returns trigger language plpgsql
set search_path = ''
as $$
begin
  insert into public.fee_tariffs
    (school_year_id, fee_type_id, category_id, class_id, amount, currency, is_active)
  select new.id, t.fee_type_id, t.category_id, t.class_id, t.amount, t.currency, t.is_active
  from public.fee_tariff_templates t
  where t.is_active
  on conflict(school_year_id, fee_type_id, class_id) do nothing;
  return new;
end;
$$;
create trigger school_year_copy_tariffs
after insert on public.school_years
for each row execute function app_private.copy_tariffs_for_year();

