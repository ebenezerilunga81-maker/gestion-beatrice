  new_data jsonb,
  reason text,
  occurred_at timestamptz not null default now()
);
create index audit_logs_occurred_idx on public.audit_logs(occurred_at desc);

-- ---------------------------------------------------------------------------
-- 5. Fonctions d'identité et d'autorisation
-- SECURITY DEFINER : search_path vide, objets qualifiés, EXECUTE restreint.
