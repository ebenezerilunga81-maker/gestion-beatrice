create extension if not exists pgcrypto;

create schema if not exists app_private;
revoke all on schema app_private from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- 1. Référentiels et profils
-- ---------------------------------------------------------------------------

create table public.profiles (
  id uuid primary key default gen_random_uuid(),
  auth_user_id uuid not null unique references auth.users(id) on delete restrict,
  full_name text not null,
  username text unique,
  role text not null check (role in ('ADMINISTRATEUR','PREFET','CAISSIER')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.school_years (
  id uuid primary key default gen_random_uuid(),
  label text not null unique,
  start_date date not null,
  end_date date not null,
  opening_date date not null,
  is_active boolean not null default false,
  created_at timestamptz not null default now(),
  check (end_date > start_date),
  check (opening_date >= start_date and opening_date <= end_date)
);
create unique index school_year_one_active_idx on public.school_years(is_active) where is_active;

create table public.holidays (
  id uuid primary key default gen_random_uuid(),
  holiday_date date not null unique,
  label text not null,
  country_code char(2) not null default 'CD',
  is_official boolean not null default true
);

create table public.categories (
  id smallint generated by default as identity primary key,
  code text not null unique,
  name text not null unique
);

create table public.classes (
  id smallint generated by default as identity primary key,
  category_id smallint not null references public.categories(id) on delete restrict,
  code text not null unique,
  name text not null,
  level_order smallint not null check (level_order > 0),
  unique(category_id, level_order),
  unique(category_id, name),
  unique(id, category_id)
);

create table public.options (
  id smallint generated by default as identity primary key,
  code text not null unique,
  name text not null unique,
  is_active boolean not null default true
);

create table public.fee_types (
  id smallint generated by default as identity primary key,
  code text not null unique,
  name text not null unique,
  is_active boolean not null default true
);

-- ---------------------------------------------------------------------------
-- 2. Élèves et inscriptions annuelles
-- ---------------------------------------------------------------------------

create sequence public.student_number_seq start 1;

create table public.students (
  id uuid primary key default gen_random_uuid(),
  student_number text not null unique
    default ('GB-' || lpad(nextval('public.student_number_seq')::text, 7, '0')),
  full_name text not null,
  date_of_birth date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.student_enrollments (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.students(id) on delete restrict,
  school_year_id uuid not null references public.school_years(id) on delete restrict,
  category_id smallint not null references public.categories(id) on delete restrict,
  class_id smallint not null,
  option_id smallint references public.options(id) on delete restrict,
  decision text not null default 'EN_ATTENTE'
    check (decision in ('EN_ATTENTE','PROMU','REDOUBLE','SORTANT','FIN_CYCLE')),
  decision_validated_by uuid references public.profiles(id) on delete restrict,
  decision_validated_at timestamptz,
  created_at timestamptz not null default now(),
  unique(student_id, school_year_id),
  foreign key(class_id, category_id)
    references public.classes(id, category_id) on delete restrict,
  check (
    (decision = 'EN_ATTENTE' and decision_validated_by is null and decision_validated_at is null)
    or
    (decision <> 'EN_ATTENTE' and decision_validated_by is not null and decision_validated_at is not null)
  )
);
create index enrollments_year_class_idx on public.student_enrollments(school_year_id, class_id);
create index enrollments_student_idx on public.student_enrollments(student_id);

-- Options uniquement pour les humanités ; option obligatoire en humanités.
create function app_private.check_enrollment_option()
returns trigger language plpgsql
set search_path = ''
as $$
declare v_category text;
begin
  select c.code into v_category
  from public.categories c where c.id = new.category_id;

  if v_category = 'HUMANITE' and new.option_id is null then
    raise exception 'Une option est obligatoire pour les classes des humanités.';
  elsif v_category <> 'HUMANITE' and new.option_id is not null then
    raise exception 'Une option ne peut être attribuée qu’aux humanités.';
  end if;
  return new;
end;
$$;
create trigger enrollment_option_guard
before insert or update of category_id, option_id on public.student_enrollments
for each row execute function app_private.check_enrollment_option();

