create function public.current_profile_id()
returns uuid language sql stable security definer
set search_path = ''
as $$
  select p.id from public.profiles p
  where p.auth_user_id = (select auth.uid()) and p.is_active = true
  limit 1;
$$;

create function public.current_app_role()
returns text language sql stable security definer
set search_path = ''
as $$
  select p.role from public.profiles p
  where p.auth_user_id = (select auth.uid()) and p.is_active = true
  limit 1;
$$;

revoke all on function public.current_profile_id() from public, anon;
revoke all on function public.current_app_role() from public, anon;
grant execute on function public.current_profile_id() to authenticated;
grant execute on function public.current_app_role() to authenticated;

-- ---------------------------------------------------------------------------
-- 6. Création de l'année scolaire avec premier lundi de septembre
-- Les jours fériés doivent être saisis avant de créer l'année.
-- ---------------------------------------------------------------------------

create function public.create_school_year(
  p_label text,
  p_start_date date,
  p_end_date date
)
returns uuid language plpgsql security definer
set search_path = ''
as $$
declare
  v_id uuid;
  v_opening date;
  v_actor uuid;
  v_role text;
begin
  v_actor := public.current_profile_id();
  v_role := public.current_app_role();
  if v_actor is null or v_role <> 'ADMINISTRATEUR' then
    raise exception 'Action réservée à l’administrateur.';
  end if;
  if p_end_date <= p_start_date then
    raise exception 'La date de fin doit être postérieure à la date de début.';
  end if;

  v_opening := make_date(extract(year from p_start_date)::int, 9, 1);
  v_opening := v_opening + ((8 - extract(isodow from v_opening)::int) % 7);

  while extract(isodow from v_opening)::int in (6,7)
     or exists (
       select 1 from public.holidays h
       where h.holiday_date = v_opening and h.is_official and h.country_code = 'CD'
     )
  loop
    v_opening := v_opening + 1;
  end loop;

  insert into public.school_years(label,start_date,end_date,opening_date)
  values(p_label,p_start_date,p_end_date,v_opening)
  returning id into v_id;
  return v_id;
end;
$$;

revoke all on function public.create_school_year(text,date,date) from public, anon;
grant execute on function public.create_school_year(text,date,date) to authenticated;

-- ---------------------------------------------------------------------------
-- 7. Paiement sécurisé : décision validée, année ouverte, tarif cohérent,
-- plafond cumulé respecté, ticket généré dans la même transaction.
-- Une inscription de l'année active n'est créée qu'après admission/validation administrative.
-- La décision EN_ATTENTE de cette inscription concerne son passage futur, pas son paiement actuel.
-- ---------------------------------------------------------------------------

create function public.register_payment(
  p_enrollment_id uuid,
  p_fee_tariff_id uuid,
  p_amount numeric,
  p_notes text default null
)
returns table(payment_id uuid, ticket_number text, remaining_balance numeric, currency char(3))
language plpgsql security definer
set search_path = ''
as $$
declare
  v_profile uuid;
  v_role text;
  v_enrollment public.student_enrollments%rowtype;
  v_year public.school_years%rowtype;
  v_tariff public.fee_tariffs%rowtype;
  v_paid numeric(14,2);
  v_reference text;
  v_ticket text;
  v_payment_id uuid;
begin
  v_profile := public.current_profile_id();
  v_role := public.current_app_role();
  if v_profile is null or v_role <> 'CAISSIER' then
    raise exception 'Seul un caissier actif peut encaisser.';
  end if;
  if p_amount is null or p_amount <= 0 then
    raise exception 'Le montant doit être supérieur à zéro.';
  end if;

  select * into v_enrollment
  from public.student_enrollments
  where id = p_enrollment_id
  for update;
  if not found then raise exception 'Inscription introuvable.'; end if;
  select * into v_year from public.school_years
  where id = v_enrollment.school_year_id;
  if not found or not v_year.is_active
     or (now() at time zone 'Africa/Kinshasa')::date < v_year.opening_date then
    raise exception 'La caisse de cette année scolaire n’est pas encore ouverte.';
  end if;

  select * into v_tariff from public.fee_tariffs
  where id = p_fee_tariff_id and is_active;
  if not found
     or v_tariff.school_year_id <> v_enrollment.school_year_id
     or v_tariff.category_id <> v_enrollment.category_id
     or v_tariff.class_id <> v_enrollment.class_id then
    raise exception 'Le tarif ne correspond pas à cette inscription.';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(
    p_enrollment_id::text || ':' || p_fee_tariff_id::text, 0
  ));

  select coalesce(sum(p.amount_paid),0) into v_paid
  from public.payments p
  where p.enrollment_id = p_enrollment_id
    and p.fee_tariff_id = p_fee_tariff_id
    and p.currency = v_tariff.currency
    and p.status = 'VALIDE';

  if v_paid + p_amount > v_tariff.amount then
    raise exception 'Ce versement dépasse le solde restant (% %).',
      (v_tariff.amount - v_paid), v_tariff.currency;
  end if;

  v_reference := 'GB-P-' || to_char(clock_timestamp() at time zone 'Africa/Kinshasa','YYYYMMDD')
    || '-' || lpad(nextval('public.ticket_number_seq')::text,8,'0');
  v_ticket := 'GB-' || to_char(clock_timestamp() at time zone 'Africa/Kinshasa','YYYY')
    || '-' || lpad(nextval('public.ticket_number_seq')::text,8,'0');

  insert into public.payments
    (enrollment_id,fee_tariff_id,cashier_id,amount_paid,currency,payment_reference,notes)
  values
    (p_enrollment_id,p_fee_tariff_id,v_profile,p_amount,v_tariff.currency,v_reference,p_notes)
  returning id into v_payment_id;

  insert into public.tickets(payment_id,ticket_number)
  values(v_payment_id,v_ticket);

  insert into public.audit_logs(actor_profile_id,action,table_name,record_id,new_data)
  values(v_profile,'PAIEMENT_ENREGISTRE','payments',v_payment_id::text,
    jsonb_build_object('amount_paid',p_amount,'currency',v_tariff.currency,'ticket',v_ticket));

  return query select v_payment_id,v_ticket,(v_tariff.amount-v_paid-p_amount),v_tariff.currency;
end;
$$;

revoke all on function public.register_payment(uuid,uuid,numeric,text) from public, anon;
grant execute on function public.register_payment(uuid,uuid,numeric,text) to authenticated;

-- ---------------------------------------------------------------------------
-- 8. Annulation contrôlée (soft delete) : préfet uniquement, motif obligatoire.
-- Le ticket et la trace restent conservés.
-- ---------------------------------------------------------------------------

create function public.annul_payment(p_payment_id uuid,p_reason text)
returns void language plpgsql security definer
set search_path = ''
as $$
declare
  v_profile uuid;
  v_role text;
  v_old public.payments%rowtype;
begin
  v_profile := public.current_profile_id();
  v_role := public.current_app_role();
  if v_profile is null or v_role <> 'PREFET' then
    raise exception 'Seul le préfet peut annuler un paiement.';
  end if;
  if p_reason is null or length(btrim(p_reason)) < 5 then
    raise exception 'Un motif précis (au moins 5 caractères) est obligatoire.';
  end if;

  select * into v_old from public.payments where id = p_payment_id for update;
  if not found or v_old.status <> 'VALIDE' then
    raise exception 'Paiement introuvable ou déjà annulé.';
  end if;

  update public.payments
  set status='ANNULE', annulled_at=now(), annulled_by=v_profile,
      annulment_reason=btrim(p_reason), updated_at=now()
  where id=p_payment_id;

  insert into public.audit_logs(actor_profile_id,action,table_name,record_id,old_data,new_data,reason)
  values(v_profile,'PAIEMENT_ANNULE','payments',p_payment_id::text,to_jsonb(v_old),
    jsonb_build_object('status','ANNULE'),btrim(p_reason));
end;
$$;
revoke all on function public.annul_payment(uuid,text) from public, anon;
grant execute on function public.annul_payment(uuid,text) to authenticated;

-- ---------------------------------------------------------------------------
-- 8 bis. Rectification d'un paiement par son caissier d'origine.
-- Le tarif, l'inscription, le caissier et la référence restent immuables.
-- ---------------------------------------------------------------------------

create function public.correct_own_payment(
  p_payment_id uuid,
  p_new_amount numeric,
  p_new_payment_date timestamptz default null,
  p_new_notes text default null
)
returns void language plpgsql security definer
set search_path = ''
as $$
declare
  v_profile uuid;
  v_role text;
  v_payment public.payments%rowtype;
  v_tariff public.fee_tariffs%rowtype;
  v_paid_other numeric(14,2);
begin
  v_profile := public.current_profile_id();
  v_role := public.current_app_role();
  if v_profile is null or v_role <> 'CAISSIER' then
    raise exception 'Seul un caissier actif peut rectifier un paiement.';
  end if;
  if p_new_amount is null or p_new_amount <= 0 then
    raise exception 'Le montant doit être supérieur à zéro.';
  end if;

  -- Même ordre de verrouillage que register_payment : inscription puis verrou métier.
  select p.* into v_payment from public.payments p where p.id=p_payment_id;
  if not found or v_payment.cashier_id <> v_profile or v_payment.status <> 'VALIDE' then
    raise exception 'Paiement introuvable, non modifiable ou appartenant à un autre caissier.';
  end if;

  perform 1 from public.student_enrollments e
  where e.id=v_payment.enrollment_id for update;
  perform pg_advisory_xact_lock(hashtextextended(
    v_payment.enrollment_id::text || ':' || v_payment.fee_tariff_id::text, 0
  ));

  select * into v_payment from public.payments p
  where p.id=p_payment_id for update;
  if v_payment.status <> 'VALIDE' or v_payment.cashier_id <> v_profile then
    raise exception 'Ce paiement n’est plus modifiable.';
  end if;

  select * into v_tariff from public.fee_tariffs
  where id=v_payment.fee_tariff_id;
  select coalesce(sum(p.amount_paid),0) into v_paid_other
  from public.payments p
  where p.enrollment_id=v_payment.enrollment_id
    and p.fee_tariff_id=v_payment.fee_tariff_id
    and p.status='VALIDE'
    and p.id <> p_payment_id;

  if v_paid_other + p_new_amount > v_tariff.amount then
    raise exception 'La rectification dépasse le solde restant (% %).',
      (v_tariff.amount-v_paid_other),v_tariff.currency;
  end if;

  update public.payments
  set amount_paid=p_new_amount,
      payment_date=coalesce(p_new_payment_date,payment_date),
      notes=p_new_notes,
      updated_at=now()
  where id=p_payment_id;

  insert into public.audit_logs(actor_profile_id,action,table_name,record_id,old_data,new_data)
  values(v_profile,'PAIEMENT_RECTIFIE','payments',p_payment_id::text,
    jsonb_build_object('amount_paid',v_payment.amount_paid,
                       'payment_date',v_payment.payment_date,'notes',v_payment.notes),
    jsonb_build_object('amount_paid',p_new_amount,
                       'payment_date',coalesce(p_new_payment_date,v_payment.payment_date),
                       'notes',p_new_notes));
end;
$$;
revoke all on function public.correct_own_payment(uuid,numeric,timestamptz,text) from public, anon;
grant execute on function public.correct_own_payment(uuid,numeric,timestamptz,text) to authenticated;

-- ---------------------------------------------------------------------------
-- 9. Décisions de fin d'année : ADMINISTRATEUR uniquement, à partir du 2 juillet.
-- PROMU crée l'inscription suivante ; REDOUBLE conserve la classe ;
-- SORTANT et FIN_CYCLE ne créent pas d'inscription suivante.
-- ---------------------------------------------------------------------------

create function public.validate_student_decision(
  p_enrollment_id uuid,
  p_decision text,
  p_next_school_year_id uuid
)
returns uuid language plpgsql security definer
set search_path = ''
as $$
declare
  v_profile uuid;
  v_role text;
  v_enrollment public.student_enrollments%rowtype;
  v_year public.school_years%rowtype;
  v_next_year public.school_years%rowtype;
  v_next_class smallint;
  v_new_enrollment uuid;
  v_class_code text;
begin
  v_profile := public.current_profile_id();
  v_role := public.current_app_role();
  if v_profile is null or v_role <> 'ADMINISTRATEUR' then
    raise exception 'Seul l’administrateur peut valider les décisions scolaires.';
  end if;
  if (now() at time zone 'Africa/Kinshasa')::date < make_date(
      extract(year from (now() at time zone 'Africa/Kinshasa'))::int,7,2) then
    raise exception 'Les décisions ne peuvent être validées qu’à partir du 2 juillet.';
  end if;
  if p_decision not in ('PROMU','REDOUBLE','SORTANT','FIN_CYCLE') then
    raise exception 'Décision invalide.';
  end if;

  select * into v_enrollment from public.student_enrollments
  where id=p_enrollment_id for update;
  if not found or v_enrollment.decision <> 'EN_ATTENTE' then
    raise exception 'Inscription introuvable ou décision déjà validée.';
  end if;
  select * into v_year from public.school_years where id=v_enrollment.school_year_id;
  if not found then raise exception 'Année scolaire introuvable.'; end if;

  select cl.code into v_class_code from public.classes cl where cl.id=v_enrollment.class_id;

  if p_decision='FIN_CYCLE' and v_class_code <> 'SEC4' then
    raise exception 'FIN_CYCLE est réservé à la 4e humanité.';
  end if;
  if p_decision='PROMU' and v_class_code in ('MAT3','PRI8','SEC4') then
    raise exception 'Cette classe est en fin de cycle : utilisez SORTANT ou FIN_CYCLE selon le cas.';
  end if;

  update public.student_enrollments
  set decision=p_decision, decision_validated_by=v_profile, decision_validated_at=now()
  where id=p_enrollment_id;

  if p_decision in ('PROMU','REDOUBLE') then
    if p_next_school_year_id is null then
      raise exception 'L’année scolaire suivante doit être créée avant la validation.';
    end if;
    select * into v_next_year from public.school_years where id=p_next_school_year_id;
    if not found or v_next_year.start_date <= v_year.start_date then
      raise exception 'Année scolaire suivante invalide.';
    end if;

    if p_decision='REDOUBLE' then
      v_next_class := v_enrollment.class_id;
    else
      select cl2.id into v_next_class
      from public.classes cl1
      join public.classes cl2
        on cl2.category_id=cl1.category_id
       and cl2.level_order=cl1.level_order+1
      where cl1.id=v_enrollment.class_id;
      if v_next_class is null then raise exception 'Classe supérieure introuvable.'; end if;
    end if;

    insert into public.student_enrollments
      (student_id,school_year_id,category_id,class_id,option_id)
    values
      (v_enrollment.student_id,p_next_school_year_id,v_enrollment.category_id,
       v_next_class,v_enrollment.option_id)
    returning id into v_new_enrollment;
  end if;

  insert into public.audit_logs(actor_profile_id,action,table_name,record_id,new_data)
  values(v_profile,'DECISION_'||p_decision,'student_enrollments',p_enrollment_id::text,
    jsonb_build_object('decision',p_decision,'next_enrollment_id',v_new_enrollment));
  return v_new_enrollment;
end;
$$;
revoke all on function public.validate_student_decision(uuid,text,uuid) from public, anon;
