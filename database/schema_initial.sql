-- GESTION BÉATRICE
-- Schéma PostgreSQL initial (brouillon à valider)
-- Cible : Supabase PostgreSQL
-- IMPORTANT : ce fichier prépare la structure. Il n'a PAS été exécuté sur Supabase.
-- Les comptes d'authentification sont gérés par Supabase Auth.
-- Les tarifs communiqués par l'établissement sont enregistrés comme grille de référence.
-- Les tarifs annuels sont automatiquement copiés depuis cette grille à la création de chaque année.
-- Un préfet/administrateur habilité pourra ensuite ajuster les tarifs de l'année concernée sans modifier les archives ni la grille de référence.

begin;

create extension if not exists pgcrypto;

-- 1. Profils applicatifs liés aux comptes Supabase Auth
create table if not exists public.profiles (
    id uuid primary key default gen_random_uuid(),
    auth_user_id uuid not null unique references auth.users(id) on delete restrict,
    full_name text not null,
    username text unique,
    role text not null check (role in ('PREFET', 'CAISSIER')),
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- 2. Années scolaires et jours fériés
create table if not exists public.school_years (
    id uuid primary key default gen_random_uuid(),
    label text not null unique, -- ex. 2026-2027
    start_date date not null,
    end_date date not null,
    opening_date date not null, -- premier lundi de septembre, reporté si jour férié
    is_active boolean not null default false,
    created_at timestamptz not null default now(),
    check (end_date > start_date)
);

create unique index if not exists one_active_school_year
    on public.school_years (is_active) where is_active = true;

create table if not exists public.holidays (
    id uuid primary key default gen_random_uuid(),
    holiday_date date not null unique,
    label text not null,
    country_code text not null default 'CD',
    is_official boolean not null default true
);

-- 3. Structure pédagogique
create table if not exists public.categories (
    id smallint generated by default as identity primary key,
    code text not null unique,
    name text not null unique
);

create table if not exists public.classes (
    id smallint generated by default as identity primary key,
    category_id smallint not null references public.categories(id) on delete restrict,
    code text not null unique,
    name text not null,
    level_order smallint not null,
    unique (category_id, level_order),
    unique (category_id, name)
);

create table if not exists public.options (
    id smallint generated by default as identity primary key,
    code text not null unique,
    name text not null unique,
    is_active boolean not null default true
);

-- 4. Identité permanente des élèves
create table if not exists public.students (
    id uuid primary key default gen_random_uuid(),
    full_name text not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- Une ligne par élève et par année : les anciennes inscriptions restent archivées.
create table if not exists public.student_enrollments (
    id uuid primary key default gen_random_uuid(),
    student_id uuid not null references public.students(id) on delete restrict,
    school_year_id uuid not null references public.school_years(id) on delete restrict,
    category_id smallint not null references public.categories(id) on delete restrict,
    class_id smallint not null references public.classes(id) on delete restrict,
    option_id smallint references public.options(id) on delete restrict,
    decision text not null default 'EN_ATTENTE'
        check (decision in ('EN_ATTENTE', 'PROMU', 'REDOUBLE', 'SORTANT')),
    decision_validated_by uuid references public.profiles(id) on delete restrict,
    decision_validated_at timestamptz,
    created_at timestamptz not null default now(),
    unique (student_id, school_year_id),
    check (
        (decision = 'EN_ATTENTE' and decision_validated_by is null and decision_validated_at is null)
        or
        (decision <> 'EN_ATTENTE' and decision_validated_by is not null and decision_validated_at is not null)
    )
);

create index if not exists enrollments_student_idx
    on public.student_enrollments(student_id);
create index if not exists enrollments_year_class_idx
    on public.student_enrollments(school_year_id, class_id);

-- 5. Frais et tarifs. Les tarifs peuvent varier par année, catégorie, classe et option.
create table if not exists public.fee_types (
    id smallint generated by default as identity primary key,
    code text not null unique,
    name text not null unique,
    is_active boolean not null default true
);

create table if not exists public.fee_tariffs (
    id uuid primary key default gen_random_uuid(),
    school_year_id uuid not null references public.school_years(id) on delete restrict,
    fee_type_id smallint not null references public.fee_types(id) on delete restrict,
    category_id smallint not null references public.categories(id) on delete restrict,
    class_id smallint references public.classes(id) on delete restrict,
    option_id smallint references public.options(id) on delete restrict,
    amount numeric(14,2) not null check (amount >= 0),
    currency char(3) not null default 'CDF',
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    -- NULLS NOT DISTINCT évite les doublons de tarifs généraux (sans classe/option).
    unique nulls not distinct
        (school_year_id, fee_type_id, category_id, class_id, option_id)
);

-- Grille tarifaire de référence communiquée pour le projet.
-- Elle est indépendante d'une année scolaire et sert à initialiser les tarifs annuels.
create table if not exists public.fee_tariff_templates (
    id uuid primary key default gen_random_uuid(),
    fee_type_id smallint not null references public.fee_types(id) on delete restrict,
    category_id smallint not null references public.categories(id) on delete restrict,
    class_id smallint not null references public.classes(id) on delete restrict,
    option_id smallint references public.options(id) on delete restrict,
    amount numeric(14,2) not null check (amount >= 0),
    currency char(3) not null check (currency in ('USD', 'CDF')),
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    unique nulls not distinct (fee_type_id, category_id, class_id, option_id)
);

-- À chaque création d'une année scolaire, recopier automatiquement la grille de référence.
-- Les tarifs annuels sont ensuite indépendants : leur modification ne touche pas le modèle
-- ni les années précédentes. Les modifications seront réservées aux rôles habilités.
create or replace function public.copy_fee_templates_to_school_year()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.fee_tariffs
        (school_year_id, fee_type_id, category_id, class_id, option_id, amount, currency, is_active)
    select
        new.id, t.fee_type_id, t.category_id, t.class_id, t.option_id,
        t.amount, t.currency, t.is_active
    from public.fee_tariff_templates t
    where t.is_active = true
    on conflict (school_year_id, fee_type_id, category_id, class_id, option_id)
    do nothing;
    return new;
end;
$$;

drop trigger if exists school_year_copy_fee_templates on public.school_years;
create trigger school_year_copy_fee_templates
after insert on public.school_years
for each row execute function public.copy_fee_templates_to_school_year();

