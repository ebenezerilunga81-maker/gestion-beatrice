-- 10. Contrôle métier des paiements : caisse seule pour la correction,
-- préfet seul pour la suppression. Les deux opérations sont auditées.
create or replace function public.guard_payment_changes()
returns trigger
language plpgsql security definer
set search_path = public
as $$
declare
    actor_role text;
    actor_id uuid;
begin
    actor_role := public.current_app_role();
    actor_id := public.current_profile_id();

    if tg_op = 'UPDATE' then
        if actor_role <> 'CAISSIER' or actor_id is null then
            raise exception 'Seul un caissier actif peut rectifier un paiement.';
        end if;
        -- L'identité de l'élève, le tarif et l'auteur d'origine ne peuvent pas être remplacés.
        if new.enrollment_id <> old.enrollment_id
           or new.fee_tariff_id <> old.fee_tariff_id
           or new.cashier_id <> old.cashier_id
           or new.payment_reference <> old.payment_reference then
            raise exception 'La rectification ne peut modifier que le montant, la date ou les notes.';
        end if;
        return new;
    elsif tg_op = 'DELETE' then
        if actor_role <> 'PREFET' or actor_id is null then
            raise exception 'Seul un préfet actif peut supprimer un paiement.';
        end if;
        return old;
    end if;
    return null;
end;
$$;

drop trigger if exists payments_guard_changes on public.payments;
create trigger payments_guard_changes
before update or delete on public.payments
for each row execute function public.guard_payment_changes();

create or replace function public.log_payment_changes()
returns trigger
language plpgsql security definer
set search_path = public
as $$
declare
    actor_id uuid;
    operation_reason text;
begin
    actor_id := public.current_profile_id();
    operation_reason := nullif(current_setting('app.audit_reason', true), '');

    if tg_op = 'INSERT' then
        insert into public.audit_logs(actor_profile_id, action, table_name, record_id, new_data)
        values (actor_id, 'INSERT', 'payments', new.id::text, to_jsonb(new));
        return new;
    elsif tg_op = 'UPDATE' then
        insert into public.audit_logs(actor_profile_id, action, table_name, record_id, old_data, new_data, reason)
        values (actor_id, 'UPDATE', 'payments', old.id::text, to_jsonb(old), to_jsonb(new), operation_reason);
        return new;
    elsif tg_op = 'DELETE' then
        if operation_reason is null then
            raise exception 'Un motif est obligatoire pour supprimer un paiement.';
        end if;
        insert into public.audit_logs(actor_profile_id, action, table_name, record_id, old_data, reason)
        values (actor_id, 'DELETE', 'payments', old.id::text, to_jsonb(old), operation_reason);
        return old;
    end if;
    return null;
end;
$$;

drop trigger if exists payments_audit_changes on public.payments;
create trigger payments_audit_changes
after insert or update or delete on public.payments
for each row execute function public.log_payment_changes();

