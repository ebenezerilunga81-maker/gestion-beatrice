on public.student_enrollments for update to authenticated
using (public.current_app_role() = 'PREFET')
with check (public.current_app_role() = 'PREFET');

create policy "payments_read_own_cashier_or_prefet"
on public.payments for select to authenticated
using (
    public.current_app_role() = 'PREFET'
    or (public.current_app_role() = 'CAISSIER' and cashier_id = public.current_profile_id())
);

create policy "payments_insert_cashier_active_year"
on public.payments for insert to authenticated
with check (
    public.current_app_role() = 'CAISSIER'
    and cashier_id = public.current_profile_id()
    and exists (
        select 1
        from public.student_enrollments e
        join public.school_years y on y.id = e.school_year_id
        join public.fee_tariffs t on t.id = fee_tariff_id
        where e.id = enrollment_id
          and y.is_active = true
          and t.school_year_id = e.school_year_id
          and t.category_id = e.category_id
          and (t.class_id is null or t.class_id = e.class_id)
          and (t.option_id is null or t.option_id = e.option_id)
          and t.is_active = true
    )
);

create policy "payments_update_cashier_only"
on public.payments for update to authenticated
using (public.current_app_role() = 'CAISSIER' and cashier_id = public.current_profile_id())
with check (public.current_app_role() = 'CAISSIER' and cashier_id = public.current_profile_id());

create policy "payments_delete_prefet_only"
on public.payments for delete to authenticated
using (public.current_app_role() = 'PREFET');

create policy "tickets_read_authenticated"
on public.tickets for select to authenticated
using (public.current_profile_id() is not null);

create policy "tickets_insert_cashier"
on public.tickets for insert to authenticated
with check (
    public.current_app_role() = 'CAISSIER'
    and exists (
        select 1 from public.payments p
        where p.id = payment_id and p.cashier_id = public.current_profile_id()
    )
);

